await p.screenshot({ path: `${OUT}/5-noms.png` });
const sel = p.locator('tr:has-text("Bob L.") select');
await sel.selectOption({ index: 1 });
await p.waitForSelector('text=Tous les noms sont reconnus');
await p.click('nav button:has-text("Tableau")');
await p.waitForSelector('td:has-text("70 %")');
await p.screenshot({ path: `${OUT}/6-tableau-complet.png` });
await p.setViewportSize({ width: 390, height: 800 });
await p.screenshot({ path: `${OUT}/7-mobile.png` });
console.log('erreurs console :', erreurs.length ? erreurs : 'aucune');
