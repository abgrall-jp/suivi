// Parcours dans le navigateur : connexion, premier choix, liaison, tableau, noms des élèves. Captures dans /tmp/.../scratchpad.
import { createRequire } from 'module';
const require = createRequire('/home/user/suivi/package.json');
process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8080';
const { initializeApp } = require('firebase-admin/app');
const { getFirestore } = require('firebase-admin/firestore');
const db = getFirestore(initializeApp({ projectId: 'gen-lang-client-0301284188' }), 'suivi-eu');
for (const c of ['enseignants', 'eleves', 'correspondances']) { const s = await db.collection(c).get(); await Promise.all(s.docs.map(d => d.ref.delete())); }
const { chromium } = require('playwright');
const OUT = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const erreurs = [];
p.on('pageerror', e => erreurs.push(e.message));
p.on('console', m => { if (m.type() === 'error') erreurs.push(m.text()); });
await p.goto('http://127.0.0.1:3300/');
await p.screenshot({ path: `${OUT}/1-connexion.png` });
await p.fill('input[type=email]', 'jean@ecole.fr');
await p.fill('input[type=password]', 'secret12');
await p.click('button[type=submit]');
await p.waitForSelector('text=Bienvenue dans Suivi');
await p.click('label:has-text("Mémoriser")');
await p.click('label:has-text("Texte à trous")');
await p.screenshot({ path: `${OUT}/2-choix.png` });
await p.click('button:has-text("Continuer")');
await p.waitForSelector('text=Relier mes applications');
await p.click('button:has-text("Relier mes applications")');
await p.click('.ligne-app:has-text("Mémoriser") button:has-text("Relier avec")');
await p.waitForSelector('.ligne-app:has-text("Mémoriser") .statut.reliee');
